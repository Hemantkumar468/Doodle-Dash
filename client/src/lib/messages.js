const plural = (count, one, many = `${one}s`) => `${count} ${count === 1 ? one : many}`;
const ordinal = (value) => {
  const number = Number(value) || 0;
  const suffix = number % 100 >= 11 && number % 100 <= 13 ? 'th' : number % 10 === 1 ? 'st' : number % 10 === 2 ? 'nd' : number % 10 === 3 ? 'rd' : 'th';
  return `${number}${suffix}`;
};

