export function getErrorCode(codeOrError) {
  if (typeof codeOrError === 'string') {
    const value = codeOrError.trim();
    const text = value.toLowerCase();
    if (text.includes('timeout') || text.includes('timed out')) return 'TIMEOUT';
    if (text.includes('connect') || text.includes('network') || text.includes('offline')) return 'CONNECT_ERROR';
    return value.toUpperCase();
  }
  if (!codeOrError || typeof codeOrError !== 'object') return '';
  if (codeOrError.code) return String(codeOrError.code).trim().toUpperCase();
  if (codeOrError.error) return getErrorCode(codeOrError.error);
  const text = `${codeOrError.name || ''} ${codeOrError.message || ''}`.toLowerCase();
  if (text.includes('timeout') || text.includes('timed out')) return 'TIMEOUT';
  if (text.includes('connect') || text.includes('network') || text.includes('offline')) return 'CONNECT_ERROR';
  return '';
}

export function getFriendlyError(codeOrError) {
  const code = getErrorCode(codeOrError);
  return FRIENDLY_ERRORS[code] || messages.errors.unknown;
}

